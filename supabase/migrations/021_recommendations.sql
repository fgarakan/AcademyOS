CREATE POLICY "Staff see player recommendations"   ON player_recommendations FOR SELECT USING (academy_id = auth_academy_id() AND auth_is_staff());
CREATE POLICY "Directors review recommendations"   ON player_recommendations FOR UPDATE USING (academy_id = auth_academy_id() AND auth_is_director_or_head());
CREATE POLICY "System creates recommendations"     ON player_recommendations FOR INSERT WITH CHECK (academy_id = auth_academy_id());

CREATE POLICY "Staff see session recommendations"  ON session_recommendations FOR SELECT USING (academy_id = auth_academy_id() AND auth_is_staff());
CREATE POLICY "Staff manage session recommendations" ON session_recommendations FOR ALL USING (academy_id = auth_academy_id() AND auth_is_staff());
