-- ============================================================
-- ACADEMY OS — MIGRATION 021: RECOMMENDATIONS
-- player_recommendations, session_recommendations
--
-- Loop position:
--   ← player_priorities (020) — what to work on
--   ← decision_scores (019)   — how urgent
--   ← player_phase_states (017) — what's allowed now
--   ← player_load_aggregation (018) — fatigue constraints
--   → sessions (recommended sessions must reference this)
--   → exercises (session recs filter exercises by priority tags)
--   → player_outcomes (016) — did following the rec improve outcomes?
--   → learning system (022) — were recs accepted or overridden?
--
-- player_recommendations: strategic-level (what to focus on this week/cycle)
-- session_recommendations: tactical-level (specific sessions + exercises to run)
-- ============================================================

-- ============================================================
-- PLAYER RECOMMENDATIONS
-- Strategic development recommendations for a player.
-- One recommendation per priority cycle (typically weekly).
-- Generated by generate_player_recommendations().
-- ============================================================
CREATE TYPE recommendation_status AS ENUM (
  'pending_review',   -- generated, awaiting director/head review
  'approved',         -- accepted as-is
  'modified',         -- accepted with changes
  'overridden',       -- completely replaced by human decision
  'rejected',         -- not acting on this
  'in_progress',      -- sessions being executed to fulfill this rec
  'completed',        -- outcome recorded, loop closed
  'expired'           -- never acted on within expiry window
);

CREATE TABLE player_recommendations (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  academy_id      UUID NOT NULL REFERENCES academies(id) ON DELETE CASCADE,
  player_id       UUID NOT NULL REFERENCES players(id) ON DELETE CASCADE,

  -- Source references (the full loop)
  priority_id     UUID REFERENCES player_priorities(id),
  decision_score_id UUID REFERENCES decision_scores(id),

  -- What is recommended
  title           TEXT NOT NULL,
  description     TEXT,
  recommendation_type TEXT NOT NULL CHECK (recommendation_type IN (
    'schedule_session',       -- create specific session(s)
    'increase_competition',   -- enter more tournaments
    'reduce_load',            -- drop session frequency/intensity
    'schedule_reassessment',  -- formal evaluation needed
    'move_group',             -- player ready for different group
    'change_track',           -- switch development track
    'add_constraint',         -- injury/load management needed
    'coach_attention'         -- flag for manual coach review
  )),

  -- Specifics
  recommended_track           development_track,
  recommended_group_id        UUID REFERENCES groups(id),
  target_sessions_per_week    INTEGER,
  target_intensity_range      JSONB,  -- {"min": 2, "max": 4}
  target_block_types          block_type[],
  target_exercise_tags        TEXT[],
  suggested_reassessment_date DATE,

  -- Confidence and urgency
  confidence_score  NUMERIC(4,3) NOT NULL CHECK (confidence_score BETWEEN 0 AND 1),
  urgency           TEXT NOT NULL DEFAULT 'routine'
                    CHECK (urgency IN ('immediate', 'urgent', 'high', 'routine', 'monitor')),
  priority_level    TEXT NOT NULL DEFAULT 'medium'
                    CHECK (priority_level IN ('critical', 'high', 'medium', 'low')),

  -- Review and approval
  status            recommendation_status NOT NULL DEFAULT 'pending_review',
  reviewed_by       UUID REFERENCES profiles(id),
  reviewed_at       TIMESTAMPTZ,
  reviewer_notes    TEXT,

  -- Override (populated if status = 'modified' or 'overridden')
  override_recommendation_type TEXT,
  override_notes    TEXT,
  overridden_by     UUID REFERENCES profiles(id),
  overridden_at     TIMESTAMPTZ,

  -- Outcome link (populated when the recommendation is completed)
  outcome_ids       UUID[],   -- player_outcomes that fulfilled this
  outcome_notes     TEXT,
  completed_at      TIMESTAMPTZ,

  expires_at        TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '14 days'),
  generated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_recs_player    ON player_recommendations(player_id, status, generated_at DESC);
CREATE INDEX idx_recs_academy   ON player_recommendations(academy_id, status, urgency);
CREATE INDEX idx_recs_pending   ON player_recommendations(academy_id, expires_at)
  WHERE status = 'pending_review';

CREATE TRIGGER tr_recommendations_updated_at
  BEFORE UPDATE ON player_recommendations
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();

-- ============================================================
-- SESSION RECOMMENDATIONS
-- Tactical-level: specific sessions to run to fulfil a player_recommendation.
-- Links the strategic recommendation to concrete template + exercises.
-- ============================================================
CREATE TABLE session_recommendations (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  academy_id      UUID NOT NULL REFERENCES academies(id) ON DELETE CASCADE,
  player_id       UUID NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  recommendation_id UUID NOT NULL REFERENCES player_recommendations(id) ON DELETE CASCADE,

  -- What to run
  title           TEXT NOT NULL,
  session_type    TEXT NOT NULL CHECK (session_type IN (
    'skill_focus', 'competition_prep', 'recovery', 'assessment', 'full_training', 'match_play'
  )),
  suggested_template_id UUID REFERENCES templates(id),
  target_date     DATE,
  target_duration_min INTEGER,
  target_intensity INTEGER CHECK (target_intensity BETWEEN 1 AND 5),

  -- Block and exercise focus (integration with exercises table)
  focus_block_types   block_type[],
  focus_exercise_ids  UUID[],     -- specific exercises to include
  focus_exercise_tags TEXT[],     -- filter exercises by tags if no specific IDs

  -- Rationale
  rationale       TEXT,
  coaching_cues   TEXT[],   -- what the coach should focus on during this session

  -- Priority link (why this session matters)
  priority_id     UUID REFERENCES player_priorities(id),
  signal_ids      UUID[],   -- signals this session is designed to address

  -- Execution status
  status          TEXT NOT NULL DEFAULT 'suggested'
                  CHECK (status IN ('suggested', 'scheduled', 'completed', 'skipped')),
  executed_session_id UUID REFERENCES sessions(id),  -- session created from this rec
  outcome_id          UUID REFERENCES player_outcomes(id),

  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_session_recs_player ON session_recommendations(player_id, status, target_date);
CREATE INDEX idx_session_recs_rec    ON session_recommendations(recommendation_id);

CREATE TRIGGER tr_session_recs_updated_at
  BEFORE UPDATE ON session_recommendations
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();

