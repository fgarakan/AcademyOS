  ADD CONSTRAINT fk_outcomes_recommendation
  FOREIGN KEY (recommendation_id)
  REFERENCES player_recommendations(id);

-- ============================================================
-- GENERATE_PLAYER_RECOMMENDATIONS()
-- Creates player_recommendations and session_recommendations
-- from the current priorities + decision score.
-- Called after generate_player_priorities() or on demand.
-- ============================================================
CREATE OR REPLACE FUNCTION generate_player_recommendations(
  p_player_id  UUID,
  p_academy_id UUID,
  p_reviewer_required BOOLEAN DEFAULT true
)
RETURNS JSONB AS $$
DECLARE
  v_score     decision_scores%ROWTYPE;
  v_phase     player_phase;
  v_load      player_load_aggregation%ROWTYPE;
  v_priority  player_priorities%ROWTYPE;
  v_rec_id    UUID;
  v_srec_id   UUID;
  v_recs_created INTEGER := 0;
  v_srecs_created INTEGER := 0;
  v_template  templates%ROWTYPE;
BEGIN
  SELECT * INTO v_score FROM decision_scores WHERE player_id = p_player_id;
  v_phase := get_player_phase(p_player_id);
  SELECT * INTO v_load  FROM player_load_aggregation WHERE player_id = p_player_id;

  -- Generate a recommendation per active priority (top 3 only)
  FOR v_priority IN
    SELECT * FROM player_priorities
    WHERE player_id = p_player_id
    AND is_active = true
    AND status = 'open'
    ORDER BY priority_rank
    LIMIT 3
  LOOP
    -- Determine recommendation type from priority category
    INSERT INTO player_recommendations (
      academy_id, player_id,
      priority_id, decision_score_id,
      title, description, recommendation_type,
      target_sessions_per_week,
      target_intensity_range,
      target_block_types, target_exercise_tags,
      confidence_score, urgency, priority_level,
      status, expires_at
    ) VALUES (
      p_academy_id, p_player_id,
      v_priority.id, v_score.id,

      CASE v_priority.category
        WHEN 'technical_skill'      THEN 'Focus sessions: ' || v_priority.title
        WHEN 'competition_exposure' THEN 'Competition plan: ' || v_priority.title
        WHEN 'load_management'      THEN 'Load reduction required: ' || v_priority.title
        WHEN 'reassessment'         THEN 'Schedule assessment: ' || v_priority.title
        WHEN 'promotion_readiness'  THEN 'Promotion evaluation: ' || v_priority.title
        ELSE v_priority.title
      END,

      v_priority.description,

      CASE v_priority.category
        WHEN 'technical_skill'      THEN 'schedule_session'
        WHEN 'tactical_skill'       THEN 'schedule_session'
        WHEN 'physical_fitness'     THEN 'schedule_session'
        WHEN 'competition_exposure' THEN 'increase_competition'
        WHEN 'load_management'      THEN 'reduce_load'
        WHEN 'reassessment'         THEN 'schedule_reassessment'
        WHEN 'promotion_readiness'  THEN 'move_group'
        ELSE 'coach_attention'
      END::TEXT,

      CASE v_priority.category
        WHEN 'load_management' THEN 2  -- reduce sessions
        ELSE 3
      END,

      CASE v_priority.category
        WHEN 'load_management' THEN '{"min": 1, "max": 2}'::JSONB
        WHEN 'competition_exposure' THEN '{"min": 3, "max": 4}'::JSONB
        ELSE '{"min": 2, "max": 4}'::JSONB
      END,

      v_priority.suggested_block_types,
      v_priority.suggested_exercise_tags,

      v_priority.confidence_score,
      v_priority.urgency,
      v_priority.priority_level,

      CASE WHEN p_reviewer_required THEN 'pending_review' ELSE 'approved' END::recommendation_status,
      NOW() + INTERVAL '14 days'
    ) RETURNING id INTO v_rec_id;

    -- Update priority with back-reference
    UPDATE player_priorities SET linked_recommendation_id = v_rec_id WHERE id = v_priority.id;

    -- Generate a session recommendation for schedule_session types
    IF v_priority.category IN ('technical_skill', 'tactical_skill', 'physical_fitness') THEN
      -- Find a matching template if possible
      SELECT t.* INTO v_template
      FROM templates t
      WHERE t.academy_id = p_academy_id
      AND (
        v_priority.suggested_exercise_tags IS NULL
        OR t.tags && v_priority.suggested_exercise_tags
      )
      AND t.is_active = true
      ORDER BY t.is_default DESC, t.created_at DESC
      LIMIT 1;

      INSERT INTO session_recommendations (
        academy_id, player_id, recommendation_id,
        title, session_type,
        suggested_template_id,
        target_date, target_duration_min, target_intensity,
        focus_block_types, focus_exercise_tags,
        rationale, priority_id, signal_ids, status
      ) VALUES (
        p_academy_id, p_player_id, v_rec_id,
        'Session: ' || v_priority.title,
        CASE v_priority.category
          WHEN 'technical_skill'  THEN 'skill_focus'
          WHEN 'tactical_skill'   THEN 'competition_prep'
          WHEN 'physical_fitness' THEN 'full_training'
          ELSE 'skill_focus'
        END,
        v_template.id,
        CURRENT_DATE + 3,  -- suggest 3 days out
        90,
        CASE v_phase
          WHEN 'competition'     THEN 3
          WHEN 'pre_competition' THEN 4
          WHEN 'recovery'        THEN 2
          ELSE 4
        END,
        v_priority.suggested_block_types,
        v_priority.suggested_exercise_tags,
        v_priority.description,
        v_priority.id,
        v_priority.source_signal_ids,
        'suggested'
      ) RETURNING id INTO v_srec_id;

      v_srecs_created := v_srecs_created + 1;
    END IF;

    v_recs_created := v_recs_created + 1;
  END LOOP;

  RETURN jsonb_build_object(
    'success', true,
    'player_id', p_player_id,
    'recommendations_created', v_recs_created,
    'session_recommendations_created', v_srecs_created,
    'urgency', v_score.urgency
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- ============================================================
-- RUN_FULL_ENGINE()
-- End-to-end: score → priorities → recommendations for one player.
-- The canonical entry point after any signal or outcome.
-- ============================================================
CREATE OR REPLACE FUNCTION run_full_engine(
  p_player_id  UUID,
  p_academy_id UUID
)
RETURNS JSONB AS $$
DECLARE
  v_score_id  UUID;
  v_priority_count INTEGER;
  v_rec_result JSONB;
BEGIN
  v_score_id       := score_player(p_player_id, p_academy_id);
  v_priority_count := generate_player_priorities(p_player_id, p_academy_id);
  v_rec_result     := generate_player_recommendations(p_player_id, p_academy_id);

  RETURN jsonb_build_object(
    'success', true,
    'player_id', p_player_id,
    'score_id', v_score_id,
    'priorities_generated', v_priority_count,
    'recommendations', v_rec_result
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

